CREATE TABLE market_paypal_refund_jobs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 request_id BIGINT UNSIGNED NOT NULL UNIQUE,
 invoice_id BIGINT UNSIGNED NOT NULL,
 attempt_id BIGINT UNSIGNED NOT NULL,
 approved_by INT NOT NULL,
 amount_cents BIGINT UNSIGNED NOT NULL,
 reason VARCHAR(2000) NOT NULL,
 mode ENUM('sandbox','live') NOT NULL,
 context_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 reference CHAR(37) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 provider_refund_id VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 status ENUM('queued','pending','review','completed','failed','cancelled') NOT NULL DEFAULT 'queued',
 first_dispatch_at DATETIME NULL,
 next_check_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 lease_token CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_until DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY paypal_refund_provider(mode,provider_refund_id),
 KEY paypal_refund_due(context_hash,status,next_check_at),
 KEY paypal_refund_invoice(invoice_id,status),
 FOREIGN KEY (request_id) REFERENCES market_refund_requests(id) ON DELETE RESTRICT,
 FOREIGN KEY (invoice_id) REFERENCES market_invoices(id) ON DELETE RESTRICT,
 FOREIGN KEY (attempt_id) REFERENCES market_payment_attempts(id) ON DELETE RESTRICT,
 FOREIGN KEY (approved_by) REFERENCES users(id) ON DELETE RESTRICT,
 CHECK (amount_cents BETWEEN 1 AND 9999999999)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
