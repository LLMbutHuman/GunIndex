-- Additive; ops/migrate.php handles the optional bumped_at column.
CREATE TABLE IF NOT EXISTS market_manual_orders (
 invoice_id BIGINT UNSIGNED PRIMARY KEY,user_id INT NOT NULL,listing_id BIGINT UNSIGNED NOT NULL,
 reference VARCHAR(64) NOT NULL UNIQUE,recipient VARCHAR(190) NOT NULL,quantity INT NOT NULL,
 net_cents BIGINT UNSIGNED NOT NULL,tax_cents BIGINT UNSIGNED NOT NULL,tax_bps INT NOT NULL,
 terms_hash VARCHAR(64) NOT NULL,terms_text TEXT NOT NULL,request_key VARCHAR(64) NOT NULL UNIQUE,
 customer_claimed_at DATETIME NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(invoice_id) REFERENCES market_invoices(id) ON DELETE RESTRICT,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY(listing_id) REFERENCES market_listings(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_bump_credits (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,invoice_id BIGINT UNSIGNED NOT NULL UNIQUE,user_id INT NOT NULL,
 quantity INT NOT NULL,remaining INT NOT NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(invoice_id) REFERENCES market_invoices(id) ON DELETE RESTRICT,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_bump_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,credit_id BIGINT UNSIGNED NOT NULL,listing_id BIGINT UNSIGNED NOT NULL,user_id INT NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(credit_id) REFERENCES market_bump_credits(id) ON DELETE RESTRICT,FOREIGN KEY(listing_id) REFERENCES market_listings(id) ON DELETE RESTRICT,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT,
 KEY bump_history(listing_id,created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
