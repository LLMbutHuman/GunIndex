CREATE TABLE IF NOT EXISTS market_billing_profiles(
 user_id INT PRIMARY KEY,legal_name VARCHAR(150) NOT NULL,address_line1 VARCHAR(150) NOT NULL,address_line2 VARCHAR(150) NOT NULL DEFAULT '',
 postal_code VARCHAR(16) NOT NULL,city VARCHAR(100) NOT NULL,country_code CHAR(2) NOT NULL,vat_id VARCHAR(40) NOT NULL DEFAULT '',
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_tax_rules(
 country_code CHAR(2) PRIMARY KEY,basis_points INT NOT NULL,explanation VARCHAR(300) NOT NULL,reviewed_by INT NOT NULL,
 reviewed_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(reviewed_by) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT approved_tax_range CHECK(basis_points BETWEEN 0 AND 10000)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_invoice_snapshots(
 invoice_id BIGINT UNSIGNED PRIMARY KEY,user_id INT NOT NULL,payload_ciphertext MEDIUMTEXT NOT NULL,payload_hash CHAR(64) NOT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(invoice_id) REFERENCES market_invoices(id) ON DELETE RESTRICT,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_invoice_sequences(
 calendar_year INT PRIMARY KEY,next_number BIGINT UNSIGNED NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_invoice_documents(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,invoice_id BIGINT UNSIGNED NOT NULL,origin_invoice_id BIGINT UNSIGNED NULL UNIQUE,
 document_number VARCHAR(80) NOT NULL UNIQUE,document_type VARCHAR(20) NOT NULL,related_document_id BIGINT UNSIGNED NULL,
 amount_cents BIGINT UNSIGNED NOT NULL,currency CHAR(3) NOT NULL DEFAULT 'EUR',payload_ciphertext MEDIUMTEXT NOT NULL,content_hash CHAR(64) NOT NULL,
 created_by INT NULL,issued_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(invoice_id) REFERENCES market_invoices(id) ON DELETE RESTRICT,
 FOREIGN KEY(related_document_id) REFERENCES market_invoice_documents(id) ON DELETE RESTRICT,
 FOREIGN KEY(created_by) REFERENCES users(id) ON DELETE RESTRICT,KEY document_invoice(invoice_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_refund_requests(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,invoice_id BIGINT UNSIGNED NOT NULL,user_id INT NOT NULL,requested_cents BIGINT UNSIGNED NOT NULL,
 status VARCHAR(24) NOT NULL DEFAULT 'requested',reason TEXT NOT NULL,decision_reason TEXT NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(invoice_id) REFERENCES market_invoices(id) ON DELETE RESTRICT,FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT,
 KEY refund_queue(status,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_refunds(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,invoice_id BIGINT UNSIGNED NOT NULL,request_id BIGINT UNSIGNED NULL,
 transaction_id VARCHAR(64) NOT NULL UNIQUE,amount_cents BIGINT UNSIGNED NOT NULL,currency CHAR(3) NOT NULL DEFAULT 'EUR',
 verified_by INT NOT NULL,reason TEXT NOT NULL,credit_document_id BIGINT UNSIGNED NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(invoice_id) REFERENCES market_invoices(id) ON DELETE RESTRICT,
 FOREIGN KEY(request_id) REFERENCES market_refund_requests(id) ON DELETE RESTRICT,
 FOREIGN KEY(verified_by) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY(credit_document_id) REFERENCES market_invoice_documents(id) ON DELETE RESTRICT,KEY refund_invoice(invoice_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_finance_events(
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,invoice_id BIGINT UNSIGNED NOT NULL,actor_id INT NULL,kind VARCHAR(50) NOT NULL,
 amount_cents BIGINT NOT NULL,currency CHAR(3) NOT NULL DEFAULT 'EUR',reference VARCHAR(128) NOT NULL UNIQUE,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(invoice_id) REFERENCES market_invoices(id) ON DELETE RESTRICT,FOREIGN KEY(actor_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
