CREATE TABLE market_bitcoin_orders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 invoice_id BIGINT UNSIGNED NOT NULL UNIQUE,
 attempt_id BIGINT UNSIGNED NOT NULL UNIQUE,
 reference CHAR(31) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 chain ENUM('main','regtest') NOT NULL,
 context_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 address VARCHAR(90) CHARACTER SET ascii COLLATE ascii_bin NULL,
 amount_sats BIGINT UNSIGNED NOT NULL,
 rate_cents_per_btc BIGINT UNSIGNED NOT NULL,
 required_confirmations TINYINT UNSIGNED NOT NULL,
 expires_at DATETIME NOT NULL,
 status ENUM('allocating','pending','confirmed','expired','review') NOT NULL DEFAULT 'allocating',
 review_reason VARCHAR(16) CHARACTER SET ascii COLLATE ascii_bin NULL,
 txid CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 vout INT UNSIGNED NULL,
 block_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL,
 confirmations INT NULL,
 next_check_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 lease_token CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NULL,
 lease_until DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY bitcoin_address(chain,address),
 UNIQUE KEY bitcoin_outpoint(chain,txid,vout),
 KEY bitcoin_work(context_hash,status,next_check_at),
 FOREIGN KEY (invoice_id) REFERENCES market_invoices(id) ON DELETE RESTRICT,
 FOREIGN KEY (attempt_id) REFERENCES market_payment_attempts(id) ON DELETE RESTRICT,
 CHECK (amount_sats BETWEEN 1 AND 2100000000000000),
 CHECK (rate_cents_per_btc>0 AND required_confirmations BETWEEN 1 AND 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
