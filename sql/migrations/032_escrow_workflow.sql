CREATE TABLE market_escrow_cases (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 listing_id BIGINT UNSIGNED NOT NULL,
 seller_id INT NOT NULL,
 buyer_id INT NOT NULL,
 proposer_id INT NOT NULL,
 reference CHAR(28) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 payment_reference CHAR(28) CHARACTER SET ascii COLLATE ascii_bin NOT NULL UNIQUE,
 listing_hash CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 price_cents BIGINT UNSIGNED NOT NULL,
 shipping_cents BIGINT UNSIGNED NOT NULL,
 currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NOT NULL DEFAULT 'EUR',
 status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 version INT UNSIGNED NOT NULL DEFAULT 1,
 create_key CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 seller_contact_cipher MEDIUMTEXT NULL,
 buyer_contact_cipher MEDIUMTEXT NULL,
 deadline DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 UNIQUE KEY escrow_created_once(seller_id,create_key),
 KEY escrow_listing_status(listing_id,status),
 KEY escrow_deadline(deadline,id),
 KEY escrow_seller(seller_id,id),
 KEY escrow_buyer(buyer_id,id),
 CHECK (buyer_id<>seller_id AND proposer_id IN (seller_id,buyer_id)),
 CHECK (price_cents>0 AND price_cents<=9999999999 AND shipping_cents<=9999999999 AND currency='EUR'),
 CHECK (status IN ('offered','awaiting_funding','payment_failed','funded','shipped','received','disputed','release_pending','refund_pending','released','refunded','charged_back','cancelled','expired','rejected')),
 CHECK ((deadline IS NOT NULL) = (status IN ('offered','awaiting_funding','payment_failed','funded','shipped'))),
 FOREIGN KEY(listing_id) REFERENCES market_listings(id) ON DELETE RESTRICT,
 FOREIGN KEY(seller_id) REFERENCES users(id) ON DELETE RESTRICT,
 FOREIGN KEY(buyer_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE market_escrow_events (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 case_id BIGINT UNSIGNED NOT NULL,
 actor_id INT NULL,
 actor_role VARCHAR(12) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 action VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 from_status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NULL,
 to_status VARCHAR(24) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 version_after INT UNSIGNED NOT NULL,
 request_key CHAR(32) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
 details_cipher MEDIUMTEXT NULL,
 provider_event_id CHAR(64) CHARACTER SET ascii COLLATE ascii_bin NULL UNIQUE,
 provider_amount_cents BIGINT UNSIGNED NULL,
 provider_currency CHAR(3) CHARACTER SET ascii COLLATE ascii_bin NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY escrow_revision(case_id,version_after),
 UNIQUE KEY escrow_request(case_id,request_key),
 CHECK ((actor_role='provider' AND provider_event_id IS NOT NULL AND provider_amount_cents IS NOT NULL AND provider_currency='EUR')
     OR (actor_role<>'provider' AND provider_event_id IS NULL AND provider_amount_cents IS NULL AND provider_currency IS NULL)),
 FOREIGN KEY(case_id) REFERENCES market_escrow_cases(id) ON DELETE RESTRICT,
 FOREIGN KEY(actor_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
