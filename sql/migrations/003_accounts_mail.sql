ALTER TABLE users ADD COLUMN email_verified_at DATETIME NULL;
CREATE TABLE IF NOT EXISTS market_auth_tokens (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,purpose VARCHAR(16) NOT NULL,
 token_hash CHAR(64) NOT NULL UNIQUE,email_hash CHAR(64) NOT NULL,auth_version INT NOT NULL,
 expires_at DATETIME NOT NULL,used_at DATETIME NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 KEY account_tokens(user_id,purpose,used_at),KEY token_expiry(expires_at),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_notifications (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id INT NOT NULL,event_key VARCHAR(128) NOT NULL,
 title VARCHAR(200) NOT NULL,body TEXT NOT NULL,target_url VARCHAR(500) NULL,is_visible TINYINT(1) NOT NULL DEFAULT 1,
 read_at DATETIME NULL,created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY notification_once(user_id,event_key),KEY notification_inbox(user_id,is_visible,read_at,id),
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_notification_preferences (
 user_id INT PRIMARY KEY,inapp_enabled TINYINT(1) NOT NULL DEFAULT 1,mail_enabled TINYINT(1) NOT NULL DEFAULT 0,
 updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS market_mail_queue (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,user_id INT NULL,dedupe_key VARCHAR(190) NOT NULL UNIQUE,
 payload_ciphertext MEDIUMTEXT NOT NULL,status VARCHAR(16) NOT NULL DEFAULT 'pending',attempts INT NOT NULL DEFAULT 0,
 next_attempt_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,processing_token CHAR(32) NULL,locked_until DATETIME NULL,
 last_error_code VARCHAR(32) NULL,delivered_at DATETIME NULL,
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 KEY mail_due(status,next_attempt_at,locked_until,id),FOREIGN KEY(user_id) REFERENCES users(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
